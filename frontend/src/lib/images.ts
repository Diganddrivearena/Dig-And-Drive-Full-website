export function getExtraImages(imageKey: string): string[] {
  const folderName = slugToFolder[imageKey];
  if (!folderName) return [];
  
  const images: string[] = [];
  for (const path in allExtraImages) {
    if (path.includes(`/${folderName}/`)) {
      images.push(allExtraImages[path].default);
    }
  }
  return images;
}
